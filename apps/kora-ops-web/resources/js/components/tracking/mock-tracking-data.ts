function makeHistory(
    baseLat: number,
    baseLng: number,
    dLat: number,
    dLng: number,
    speed: number,
    heading: number,
): TrackingHistoricalPoint[] {
    const points: TrackingHistoricalPoint[] = [];
    const now = Date.now();

    for (let i = 5; i >= 0; i--) {
        points.push({
            uuid: `hist-${Math.random().toString(36).slice(2, 9)}`,
            latitude: Number((baseLat - dLat * i).toFixed(5)),
            longitude: Number((baseLng - dLng * i).toFixed(5)),
            speed_kmh: Math.max(20, Math.round(speed + (Math.sin(i) * 6))),
            heading_degrees: heading,
            accuracy_meters: Number((4.5 + i * 0.4).toFixed(1)),
            recorded_at: new Date(now - i * 25 * 1000).toISOString(),
            source: 'gps',
        });
    }

    return points;
}

function makeWaypointHistory(
    waypoints: [number, number][],
    speed: number,
    heading: number,
): TrackingHistoricalPoint[] {
    const now = Date.now();

    return waypoints.map(([lat, lng], index) => ({
        uuid: `hist-wp-${Math.random().toString(36).slice(2, 9)}`,
        latitude: lat,
        longitude: lng,
        speed_kmh: Math.max(20, Math.round(speed - (waypoints.length - 1 - index) * 3)),
        heading_degrees: heading,
        accuracy_meters: Number((4.5 + (waypoints.length - 1 - index) * 0.5).toFixed(1)),
        recorded_at: new Date(now - (waypoints.length - 1 - index) * 30 * 1000).toISOString(),
        source: 'gps',
    }));
}

